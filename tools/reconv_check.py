#!/usr/bin/env python3
"""Check a re-conversion output file against its source batch.

Usage: python -I tools/reconv_check.py decomp/text/kanji_r14/batch_NN.txt
(the kana source batches are regenerated by python -I tools/reconv_prep.py)

Reports missing/extra blocks, changed runtime tokens, characters the game
cannot show, spaces, waits placed mid-sentence, glossary deviations and
kanji missing from every font.  Exit status 1 when any error is found.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REC = ROOT / "out" / "reconv"
sys.path.insert(0, str(ROOT / "tools"))

HIRA = set("あいうえおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろわをんゔ")
KATA = set("アイウエオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナネハバパヒビピフブプホボポマミムメモヤュユョヨラリルレロワンヴー")
OTHER = set("０１２３４５６７８９「！？ー-＊★／、。|/▼")
KANJI = re.compile(r"[々㐀-鿿豈-﫿]")
TOKEN = re.compile(r"<[^<>]*>")
RUNTIME = re.compile(r"<(NAME_F[3-7]|CALL:[0-9A-F]{4}(?:=[^>]*)?|JUMP:[0-9A-F]{4}|WAIT|END|END_NOWAIT)>")


def blocks(path: Path) -> list[tuple[str, str]]:
    out = []
    lines = path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        if lines[i].startswith("@"):
            head = lines[i].strip()
            body = lines[i + 1] if i + 1 < len(lines) else ""
            out.append((head, body.rstrip("\n")))
            i += 2
        else:
            i += 1
    return out


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    outp = Path(sys.argv[1])
    src = REC / outp.name                     # kana source: tools/reconv_prep.py
    if not src.exists():
        src = REC / outp.name.replace(".out", "")
    sblocks = dict(blocks(src))
    oblocks = blocks(outp)
    errors: list[str] = []
    seen = set()
    gloss = {}
    gpath = ROOT / "decomp" / "text" / "kanji_r14" / "glossary.tsv"
    if gpath.exists():
        for line in gpath.read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#"):
                parts = line.split("\t")
                if len(parts) >= 3:
                    gloss[parts[1]] = parts[2]
    try:
        from kanji_common import glyph_available
    except Exception:
        glyph_available = None
    font_cache: dict[str, bool] = {}
    for head, body in oblocks:
        if head in seen:
            errors.append(f"{head}: duplicate block")
        seen.add(head)
        if head not in sblocks:
            errors.append(f"{head}: not in the source batch")
            continue
        s = sblocks[head]
        if [m.group(0) for m in RUNTIME.finditer(s)] != [m.group(0) for m in RUNTIME.finditer(body)]:
            errors.append(f"{head}: runtime tokens differ from the source")
        stray = [t for t in TOKEN.findall(body) if not RUNTIME.fullmatch(t)]
        if stray:
            errors.append(f"{head}: unknown token(s) {stray}")
        plain = TOKEN.sub("", body)
        for ch in plain:
            if ch in (" ", "　"):
                errors.append(f"{head}: space in text (write none; use 、 for a pause)")
                break
        bad = sorted({ch for ch in plain if not (ch in HIRA or ch in KATA or ch in OTHER or KANJI.match(ch) or ch in " 　")})
        if bad:
            errors.append(f"{head}: characters the font cannot show: {''.join(bad)}")
        for m in re.finditer(r"([㐀-鿿])\1", plain):
            errors.append(f"{head}: {m.group(0)} repeats a kanji (write {m.group(1)}々)")
        if "」" in plain:
            errors.append(f"{head}: closing 」 is not available")
        for m in re.finditer("▼", body):
            before = TOKEN.sub("", body[:m.start()]).replace("|", "").rstrip("/")
            if before and not before.endswith(("。", "！", "？", "-", "」")):
                errors.append(f"{head}: ▼ not at a sentence end: ...{before[-8:]}▼")
        for seg in re.split(r"[|/▼、。！？]", TOKEN.sub("ＮＮＮＮ", body)):
            w = sum(2 if KANJI.match(c) else 1 for c in seg)
            if w > 16:
                errors.append(f"{head}: phrase '{seg[:10]}...' is {w} cells without a | break (max 16)")
        if "||" in body or body.startswith("|"):
            errors.append(f"{head}: empty phrase between |")
        vis_src = TOKEN.sub("", s).replace("/", "").replace("▼", "").strip("　 ")
        if vis_src and not plain.replace("|", "").replace("/", "").replace("▼", ""):
            errors.append(f"{head}: converted text is empty")
        if glyph_available:
            for ch in set(KANJI.findall(plain)):
                if ch not in font_cache:
                    font_cache[ch] = bool(glyph_available and glyph_available(ch))
                if not font_cache[ch]:
                    errors.append(f"{head}: kanji {ch} has no MS Gothic bitmap or composite")
        for kana, kanji in gloss.items():
            if kana and len(kana) >= 3 and kana in TOKEN.sub("", s).replace("　", "") and kanji and kanji not in plain:
                pass  # informational only; glossary use is checked by review
    missing = [h for h in sblocks if h not in seen]
    for h in missing:
        errors.append(f"{h}: missing from the output")
    for e in errors:
        print(e)
    print(f"{outp.name}: {len(oblocks)} blocks, {len(errors)} errors")
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
