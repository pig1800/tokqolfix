#!/usr/bin/env python3
"""Build the 512 KiB kanji-target resources.

Owns the patched fixed bank, the RAM overlay source bank, the bank-13
far-text trampoline, the font banks and the generated text/metadata banks.
The original 256 KiB target never runs this script.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROM = ROOT / "Tenchi o Kurau (Japan) (Rev 1).nes"
OUT = ROOT / "decomp" / "build" / "kanji"
ASM = ROOT / "tools" / "asm"
ASM6F = ROOT / "tools" / "toolchain" / "asm6f" / "asm6f_64.exe"

KANJI_SIG = bytes((0x4B, 0x4F))      # "KO"
OVERLAY_BANK = 24
OVERLAY_SIZE = 0x400

# Fixed-bank patch sites and the original bytes they replace.  Any mismatch
# means the baseline changed and the patch needs re-auditing.
PATCH_SITES = {
    0xC4B7: bytes((0x8D, 0xF9, 0xFF)),   # write_prg_bank prologue
    0xD1FA: bytes((0x4C, 0x7E, 0xC4)),   # jmp set_bank_current
    0xD28E: bytes((0xB0, 0x27, 0xC9)),   # bcs / cmp #$EF
    0xD2BB: bytes((0x20, 0x40, 0xD3)),   # jsr text_put_tile
    0xD2C7: bytes((0x9D, 0x00, 0x03)),   # sta $0300,x
    0xEE7F: bytes((0xA5, 0xEC, 0xD0)),   # lda nmi_busy / bne
    0xEECB: bytes((0x20, 0xFF, 0xC2)),   # jsr flush_palette
}


def read_labels(listing: Path) -> dict[str, int]:
    labels: dict[str, int] = {}
    for line in listing.read_text(encoding="utf-8", errors="ignore").splitlines():
        m = re.match(r"^0([0-9A-Fa-f]{4})\s+([A-Za-z_][A-Za-z0-9_]*):", line)
        if m:
            labels[m.group(2)] = int(m.group(1), 16)
    return labels


def prg() -> bytes:
    return ROM.read_bytes()[16:]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_bank(name: str, data: bytes) -> None:
    assert len(data) == 0x4000, (name, len(data))
    (OUT / name).write_bytes(data)


def assemble(name: str) -> bytes:
    src = ASM / f"{name}.asm"
    dst = OUT / f"{name}.bin"
    lst = OUT / f"{name}.lst"
    cmd = [str(ASM6F), str(src), str(dst), "-l", str(lst)]
    result = subprocess.run(cmd, cwd=ASM, text=True, capture_output=True)
    if result.stdout:
        print(result.stdout, end="")
    if result.stderr:
        print(result.stderr, end="", file=sys.stderr)
    if result.returncode != 0:
        raise SystemExit(f"assembly failed: {name}")
    return dst.read_bytes()


def write_hook_constants(labels: dict[str, int]) -> None:
    wanted = {
        "RAM_TEXT_DISPATCH": "text_dispatch",
        "RAM_KANJI_EC": "KANJI_EC",
        "RAM_UPLOAD_GLYPH": "upload_glyph",
        "RAM_CTRL_STORE": "ctrl_store",
        "RAM_KANA_PREPARE": "kana_prepare",
        "RAM_RESTORE_ALL": "restore_all",
        "RAM_META_LOAD": "meta_load",
        "RAM_BANK_SWITCH": "bank_switch_outer",
        "RAM_NMI_HOOK": "nmi_hook",
        "RAM_CHR_UPLOAD": "chr_upload",
        "RAM_EXPAND_TILE": "expand_tile",
        "RAM_NMI_ENTRY": "nmi_entry",
    }
    lines = ["; generated by tools/kanji_build.py from kanji_fixed.lst"]
    for const, label in wanted.items():
        if label not in labels:
            raise SystemExit(f"missing overlay label {label}")
        lines.append(f"{const} = ${labels[label]:04X}")
    (OUT / "fixed_hooks.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_font() -> None:
    sys.path.insert(0, str(ROOT / "tools"))
    import kanji_font
    kanji_font.build()
    font = (OUT / "kanji_font.bin").read_bytes()
    bank16 = bytearray(0x4000)
    bank17 = bytearray(0x4000)
    first = min(len(font), 0x4000)
    bank16[:first] = font[:first]
    if len(font) > 0x4000:
        second = min(len(font) - 0x4000, 0x4000)
        bank17[:second] = font[0x4000:0x4000 + second]
    write_bank("bank16.bin", bytes(bank16))
    write_bank("bank17.bin", bytes(bank17))


def build_text() -> None:
    sys.path.insert(0, str(ROOT / "tools"))
    import kanji_text
    kanji_text.build()


def build_far_head(far_block: bytes) -> None:
    original = prg()
    head = bytearray(original[13 * 0x4000:13 * 0x4000 + 0x800])
    assert far_block
    if len(far_block) > 255:
        raise SystemExit(f"far loader is {len(far_block)} bytes, max 255")
    block = far_block + bytes(0x60 for _ in range(255 - len(far_block)))
    entry = 0x0317
    head[entry:entry + 3] = bytes((0x20, 0xE4, 0xC4))  # jsr call_inline_block
    head[entry + 3:entry + 3 + 255] = block
    (OUT / "bank13_head.bin").write_bytes(bytes(head))


def build_overlay_bank(overlay: bytes) -> None:
    if len(overlay) > OVERLAY_SIZE - 2:
        raise SystemExit(f"overlay is {len(overlay)} bytes, max {OVERLAY_SIZE - 2}")
    bank = bytearray(0x4000)
    bank[0:2] = KANJI_SIG
    bank[2:2 + len(overlay)] = overlay
    write_bank(f"bank{OVERLAY_BANK:02d}.bin", bytes(bank))


def apply_patch(bank: bytearray, addr: int, data: bytes) -> None:
    off = addr - 0xC000
    original = bytes(bank[off:off + len(data)])
    want = PATCH_SITES.get(addr)
    if want is not None and original != want:
        raise SystemExit(f"patch site ${addr:04X}: expected {want.hex()}, "
                         f"found {original.hex()}")
    bank[off:off + len(data)] = data


def build_bank15(hooks: bytes, hook_labels: dict[str, int],
                 fixed_labels: dict[str, int]) -> None:
    if len(hooks) > 0xC676 - 0xC611 + 1:
        raise SystemExit(f"hook block is {len(hooks)} bytes, gap is 102 bytes")
    original = prg()
    bank = bytearray(original[15 * 0x4000:16 * 0x4000])

    # Redirect the original 20-byte PRG-only switcher to the SUROM routine in
    # the unused C611..C676 gap.
    apply_patch(bank, 0xC4B7, bytes((0x4C, 0x11, 0xC6)))
    off = 0xC611 - 0xC000
    bank[off:off + len(hooks)] = hooks

    for label in ("far_stub", "nmi_entry_guard", "nmi_palette_guard"):
        if label not in hook_labels:
            raise SystemExit(f"missing hook label {label}")
    far_stub = hook_labels["far_stub"]
    entry_guard = hook_labels["nmi_entry_guard"]
    palette_guard = hook_labels["nmi_palette_guard"]

    # Message-internal text_put_tile call sites go through the RAM
    # kana_prepare (which preserves X/Y and restores dirty kana tiles).
    # Status/item-screen call sites are left alone: the exit hook restores
    # the whole font before those screens redraw.
    kana_prepare = fixed_labels["kana_prepare"]
    for addr in (0xD32B, 0xD4C0, 0xD5C0):
        off = addr - 0xC000
        if bytes(bank[off:off + 3]) != bytes((0x20, 0x40, 0xD3)):
            raise SystemExit(f"text_put_tile call site ${addr:04X} changed")
        bank[off:off + 3] = bytes((0x20, kana_prepare & 0xFF, kana_prepare >> 8))

    apply_patch(bank, 0xD28E, bytes((0x4C, fixed_labels["text_dispatch"] & 0xFF,
                                     fixed_labels["text_dispatch"] >> 8)))
    apply_patch(bank, 0xD2BB, bytes((0x20, fixed_labels["kana_prepare"] & 0xFF,
                                     fixed_labels["kana_prepare"] >> 8)))
    apply_patch(bank, 0xD2C7, bytes((0x20, fixed_labels["ctrl_store"] & 0xFF,
                                     fixed_labels["ctrl_store"] >> 8)))
    apply_patch(bank, 0xEE7F, bytes((0x4C, entry_guard & 0xFF, entry_guard >> 8)))
    apply_patch(bank, 0xEECB, bytes((0x20, palette_guard & 0xFF, palette_guard >> 8)))

    # The far stub itself must live at the address used by the trampolines.
    if far_stub != 0xC63A:
        raise SystemExit(f"far_stub moved to ${far_stub:04X}")
    write_bank("bank15.bin", bytes(bank))


def build_bank31() -> None:
    bank15 = (OUT / "bank15.bin").read_bytes()
    write_bank("bank31.bin", bank15)


def build_skeleton() -> None:
    blank = bytes(0x4000)
    for bank in range(25, 31):
        write_bank(f"bank{bank:02d}.bin", blank)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["build"], nargs="?", default="build")
    ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    fixed = assemble("kanji_fixed")
    fixed_labels = read_labels(OUT / "kanji_fixed.lst")
    write_hook_constants(fixed_labels)

    hooks = assemble("surom_b15")
    hook_labels = read_labels(OUT / "surom_b15.lst")
    far = assemble("kanji_far")

    build_font()
    build_text()
    build_far_head(far)
    build_overlay_bank(fixed)
    build_bank15(hooks, hook_labels, fixed_labels)
    build_bank31()
    build_skeleton()
    print(f"overlay: {len(fixed)} bytes in bank {OVERLAY_BANK}; "
          f"hooks: {len(hooks)} bytes; far block: {len(far)} bytes")
    print(f"wrote kanji resources to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
