#!/usr/bin/env python3
"""Build the 512 KiB kanji-target resources.

Owns the ROM-resident text overlay, the fixed-bank trampoline, the font
banks and the generated text/metadata banks.  The original 256 KiB target
never runs this script.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROM = ROOT / "Tenchi o Kurau (Japan) (Rev 1).nes"
OUT = ROOT / "decomp" / "build" / "kanji"
ASM = ROOT / "tools" / "asm"
ASM6F = ROOT / "tools" / "toolchain" / "asm6f" / "asm6f_64.exe"

TEXT_BANK_START = 18
TEXT_BANK_END = 22
OVERLAY_LIMIT = 0x800

# Fixed-bank patch sites and the original bytes they replace.  Any mismatch
# means the baseline changed and the patch needs re-auditing.
PATCH_SITES = {
    0xC469: bytes((0x0E,)),              # mmc1_init control: 8K -> 4K CHR mode
    0xC4B7: bytes((0x8D, 0xF9, 0xFF)),   # write_prg_bank prologue
    0xD190: bytes((0x20, 0xA2, 0xC4)),   # jsr set_bank_13 (<JUMP>)
    0xD198: bytes((0x20, 0xA6, 0xC4)),   # jsr set_bank_14 (<JUMP>)
    0xD1FA: bytes((0x4C, 0x7E, 0xC4)),   # jmp set_bank_current
    0xD28E: bytes((0xB0, 0x27, 0xC9)),   # bcs / cmp #$EF
    0xD2C7: bytes((0x9D, 0x00, 0x03)),   # sta $0300,x
    0xD420: bytes((0xBD, 0x19, 0x03)),   # lda $0319,x (redraw high-tile test)
    0xDBE7: bytes((0xB9, 0x00, 0x03)),   # lda $0300,y
    0xDBEA: bytes((0x10,)),              # bpl (bit-7 control test)
    0xEEDD: bytes((0x20, 0xFC, 0xC0)),   # jsr ppu_nmi_on (NMI band stub)
    0xF022: bytes((0x00,)),              # reset CHR reg 1 immediate ($00)
    0xF036: bytes((0xA9, 0x00, 0xA2, 0xF0)),  # lda #0 / ldx #$F0
}


def prg() -> bytes:
    return ROM.read_bytes()[16:]


def write_bank(name: str, data: bytes) -> None:
    assert len(data) == 0x4000, (name, len(data))
    (OUT / name).write_bytes(data)


def assemble(name: str) -> bytes:
    src = ASM / f"{name}.asm"
    dst = OUT / f"{name}.bin"
    lst = OUT / f"{name}.lst"
    cmd = [str(ASM6F), str(src), str(dst), "-l", str(lst)]
    result = subprocess.run(cmd, cwd=ASM, text=True, capture_output=True)
    if result.stdout:
        print(result.stdout, end="")
    if result.stderr:
        print(result.stderr, end="", file=sys.stderr)
    if result.returncode != 0:
        raise SystemExit(f"assembly failed: {name}")
    return dst.read_bytes()


def read_labels(listing: Path) -> dict[str, int]:
    labels: dict[str, int] = {}
    for line in listing.read_text(encoding="utf-8", errors="ignore").splitlines():
        m = re.match(r"^0([0-9A-Fa-f]{4})\s+([A-Za-z_][A-Za-z0-9_]*):", line)
        if m:
            labels[m.group(2)] = int(m.group(1), 16)
    return labels


def write_hook_constants(labels: dict[str, int]) -> None:
    wanted = {
        "RAM_OVERLAY_ENTRY": "overlay_entry",
        "RAM_TEXT_DISPATCH": "text_dispatch",
        "RAM_CTRL_STORE": "ctrl_store",
        "RAM_EXIT_CLEAR": "exit_clear",
        "RAM_JUMP_13": "jump_exit_13",
        "RAM_JUMP_14": "jump_exit_14",
        "RAM_CELL_CHECK": "cell_check",
        "RAM_REDRAW_HIGH": "redraw_high",
        "RAM_UPLOAD_GLYPH": "upload_glyph",
        "RAM_WRITE_CHR1": "overlay_write_chr1",
    }
    lines = ["; generated by tools/kanji_build.py from kanji_overlay.lst"]
    for const, label in wanted.items():
        if label not in labels:
            raise SystemExit(f"missing overlay label {label}")
        lines.append(f"{const} = ${labels[label]:04X}")
    (OUT / "fixed_hooks.inc").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_trampoline_constants(labels: dict[str, int]) -> None:
    if "enter_text" not in labels:
        raise SystemExit("missing fixed-hook label enter_text")
    lines = [
        "; generated by tools/kanji_build.py from surom_b15.lst",
        f"WRITE_CHR1 = ${labels['write_chr1']:04X}",
        f"FAR_HEAD = ${labels['far_head']:04X}",
        f"ENTER_TEXT = ${labels['enter_text']:04X}",
    ]
    (OUT / "trampoline_hooks.inc").write_text("\n".join(lines) + "\n",
                                              encoding="utf-8")


def build_font() -> None:
    sys.path.insert(0, str(ROOT / "tools"))
    import kanji_font
    kanji_font.build()
    font = (OUT / "kanji_font.bin").read_bytes()
    bank16 = bytearray(0x4000)
    bank17 = bytearray(0x4000)
    first = min(len(font), 0x4000)
    bank16[:first] = font[:first]
    if len(font) > 0x4000:
        second = min(len(font) - 0x4000, 0x4000)
        bank17[:second] = font[0x4000:0x4000 + second]
    write_bank("bank16.bin", bytes(bank16))
    write_bank("bank17.bin", bytes(bank17))


def build_text() -> None:
    sys.path.insert(0, str(ROOT / "tools"))
    import kanji_text
    kanji_text.build()


def build_overlay(overlay: bytes) -> None:
    if len(overlay) > OVERLAY_LIMIT:
        raise SystemExit(f"overlay is {len(overlay)} bytes, max {OVERLAY_LIMIT}")
    if len(overlay) < OVERLAY_LIMIT:
        overlay = overlay + bytes(OVERLAY_LIMIT - len(overlay))
    # kanji_text.build() embeds this file at $BC00 in every text bank.
    (OUT / "kanji_overlay_padded.bin").write_bytes(overlay)


def apply_patch(bank: bytearray, addr: int, data: bytes) -> None:
    off = addr - 0xC000
    original = bytes(bank[off:off + len(data)])
    want = PATCH_SITES.get(addr)
    if want is not None and original != want:
        raise SystemExit(f"patch site ${addr:04X}: expected {want.hex()}, "
                         f"found {original.hex()}")
    bank[off:off + len(data)] = data


def build_bank15(hooks: bytes, hook_labels: dict[str, int],
                 overlay_labels: dict[str, int]) -> None:
    if len(hooks) > 0xC676 - 0xC611 + 1:
        raise SystemExit(f"hook block is {len(hooks)} bytes, gap is 102 bytes")
    original = prg()
    bank = bytearray(original[15 * 0x4000:16 * 0x4000])

    # MMC1 4 KiB CHR mode and CHR register 1 = page 1 at reset.  Both fixed
    # bank copies (15 and 31) get these patches.
    apply_patch(bank, 0xC469, bytes((0x1E,)))
    apply_patch(bank, 0xF022, bytes((0x01,)))

    # Redirect the original 20-byte PRG-only switcher to the SUROM routine in
    # the unused C611..C676 gap.
    apply_patch(bank, 0xC4B7, bytes((0x4C, 0x11, 0xC6)))
    off = 0xC611 - 0xC000
    bank[off:off + len(hooks)] = hooks

    for label in ("far_head", "enter_text", "write_chr1", "band_stub", "reset_extra"):
        if label not in hook_labels:
            raise SystemExit(f"missing hook label {label}")

    apply_patch(bank, 0xD190, bytes((0x20, overlay_labels["jump_exit_13"] & 0xFF,
                                     overlay_labels["jump_exit_13"] >> 8)))
    apply_patch(bank, 0xD198, bytes((0x20, overlay_labels["jump_exit_14"] & 0xFF,
                                     overlay_labels["jump_exit_14"] >> 8)))
    apply_patch(bank, 0xD1FA, bytes((0x4C, overlay_labels["exit_clear"] & 0xFF,
                                     overlay_labels["exit_clear"] >> 8)))
    apply_patch(bank, 0xD28E, bytes((0x4C, overlay_labels["text_dispatch"] & 0xFF,
                                     overlay_labels["text_dispatch"] >> 8)))
    apply_patch(bank, 0xD2C7, bytes((0x20, overlay_labels["ctrl_store"] & 0xFF,
                                     overlay_labels["ctrl_store"] >> 8)))
    # text_render_cell: allow tile numbers $80-$F9 through the control test.
    # The test lives in RAM because the renderer runs with the fixed bank and
    # any PRG bank mapped.
    apply_patch(bank, 0xDBE7, bytes((0x20, 0xEC, 0x01)))   # jsr $01EC
    apply_patch(bank, 0xDBEA, bytes((0x90,)))   # bcc loc_DBEF
    redraw = overlay_labels["redraw_high"]
    apply_patch(bank, 0xD420, bytes((0x4C, redraw & 0xFF, redraw >> 8)))

    # NMI band switch stub.
    apply_patch(bank, 0xEEDD, bytes((0x20, hook_labels["band_stub"] & 0xFF,
                                     hook_labels["band_stub"] >> 8)))
    # Reset hook: clear the band state before the RAM clear loop.
    apply_patch(bank, 0xF036, bytes((0x20, hook_labels["reset_extra"] & 0xFF,
                                     hook_labels["reset_extra"] >> 8, 0xEA)))

    write_bank("bank15.bin", bytes(bank))


def build_bank31() -> None:
    bank15 = (OUT / "bank15.bin").read_bytes()
    write_bank("bank31.bin", bank15)


def build_skeleton() -> None:
    blank = bytes(0x4000)
    for bank in range(TEXT_BANK_END + 1, 31):
        write_bank(f"bank{bank:02d}.bin", blank)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["build"], nargs="?", default="build")
    ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)

    overlay = assemble("kanji_overlay")
    overlay_labels = read_labels(OUT / "kanji_overlay.lst")
    write_hook_constants(overlay_labels)
    build_overlay(overlay)

    hooks = assemble("surom_b15")
    hook_labels = read_labels(OUT / "surom_b15.lst")
    write_trampoline_constants(hook_labels)
    trampoline = assemble("trampoline")
    if len(trampoline) > 0x100:
        raise SystemExit(f"trampoline is {len(trampoline)} bytes, max 256")
    (OUT / "far_stub.txt").write_text(
        f"{hook_labels['far_head']:04X}\n", encoding="utf-8")

    build_font()
    build_text()
    build_bank15(hooks, hook_labels, overlay_labels)
    build_bank31()
    build_skeleton()
    print(f"overlay: {len(overlay)} bytes at $B800 in banks "
          f"{TEXT_BANK_START}-{TEXT_BANK_END}; hooks: {len(hooks)} bytes")
    print(f"wrote kanji resources to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
